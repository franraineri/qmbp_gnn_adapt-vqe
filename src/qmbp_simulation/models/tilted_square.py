"""Tilted square clusters with periodic boundary conditions.

Standard finite-size exact diagonalization of frustrated 2D models does NOT use
open rectangular grids — those break the point-group symmetry (truncated grids)
or induce spurious boundary degeneracy (clean grids with open edges). Instead it
uses *tilted clusters* with periodic boundary conditions, defined by a tilt
vector (L1, L2). The cluster holds N = L1^2 + L2^2 sites and preserves the full
C4v point symmetry of the infinite lattice while being free of open boundaries.

The magic numbers N = L1^2 + L2^2 are: 8 (2,2), 10 (3,1), 16 (4,0), 18 (3,3),
20 (4,2), 25 (5,0)/(3,4), 26 (5,1), 32 (4,4), 36 (6,0), 40 (6,2).

Geometry
--------
The periodic cell is spanned by the two orthogonal tilt vectors
    T1 = (L1, L2),   T2 = (-L2, L1).
Their determinant L1^2 + L2^2 = N equals the number of sites. Every point of Z^2
is folded back into one canonical representative modulo the lattice generated by
T1, T2. Sites are those representatives. Bonds wrap across the cell:
    nn  = displacements (+1,0), (0,+1)         (axial, J1)
    nnn = displacements (+1,+1), (+1,-1)       (diagonal, J2)
each folded through the periodic cell. Because there is no boundary, every site
has exactly z=4 nn and z=4 nnn neighbours.

This module is independent of ``generate_square`` (open rectangular grid), which
remains the model studied elsewhere. PBC is a *different physical model*.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class TiltedCluster:
    """A tilted square cluster with PBC.

    Attributes
    ----------
    l1, l2 : int
        Tilt vector components. N = l1^2 + l2^2.
    n_qubits : int
        Number of sites (= l1^2 + l2^2).
    coords : list[tuple[int, int]]
        Canonical (x, y) integer coordinate of each site, indexed by site id.
    nn_edges : list[tuple[int, int]]
        Nearest-neighbour bonds (axial, J1), as sorted (min, max) site pairs.
    nnn_edges : list[tuple[int, int]]
        Next-nearest-neighbour bonds (diagonal, J2), sorted (min, max) pairs.
    """

    l1: int
    l2: int
    n_qubits: int
    coords: list[tuple[int, int]]
    nn_edges: list[tuple[int, int]]
    nnn_edges: list[tuple[int, int]]


def _fold(x: int, y: int, l1: int, l2: int, n: int) -> tuple[int, int]:
    """Fold a Z^2 point into the canonical cell modulo the tilt lattice.

    The periodic lattice is generated by T1=(l1,l2), T2=(-l2,l1). A point p is
    equivalent to p - a*T1 - b*T2 for integers a, b. We solve for the (a, b) that
    bring p closest to the origin, using the exact integer inverse of the
    generator matrix (its determinant is n), then pick the representative with
    minimal (y, x) after a bounded local search to guarantee a unique canonical
    point independent of the starting coset member.
    """
    # Integer inverse of [[l1, -l2], [l2, l1]] scaled by det = n:
    #   [a, b]^T = (1/n) [[l1, l2], [-l2, l1]] [x, y]^T
    # Round to the nearest integer lattice translation, subtract, then do a small
    # neighbour search to land on the canonical (minimal) representative.
    a = round((l1 * x + l2 * y) / n)
    b = round((-l2 * x + l1 * y) / n)
    bx = x - (a * l1 - b * l2)
    by = y - (a * l2 + b * l1)
    best = (bx, by)
    # Local search over adjacent translations to guarantee the canonical rep.
    for da in (-1, 0, 1):
        for db in (-1, 0, 1):
            cx = bx - (da * l1 - db * l2)
            cy = by - (da * l2 + db * l1)
            if (cx * cx + cy * cy, cy, cx) < (best[0] * best[0] + best[1] * best[1], best[1], best[0]):
                best = (cx, cy)
    return best


def generate_square_tilted(l1: int, l2: int) -> TiltedCluster:
    """Build a tilted square cluster with PBC for tilt vector (l1, l2).

    Parameters
    ----------
    l1, l2 : int
        Tilt vector components (non-negative, not both zero). N = l1^2 + l2^2.

    Returns
    -------
    TiltedCluster
        Sites, nn (axial J1) and nnn (diagonal J2) bonds, all wrapped through
        the periodic cell. Every site has exactly 4 nn and 4 nnn neighbours.
    """
    if l1 < 0 or l2 < 0 or (l1 == 0 and l2 == 0):
        raise ValueError(f"tilt (l1, l2) must be non-negative and non-zero, got ({l1}, {l2})")
    n = l1 * l1 + l2 * l2

    # Enumerate N distinct canonical representatives by folding a generous window
    # of Z^2 points. The window must cover the cell; |l1|+|l2| in each direction
    # is more than enough.
    span = l1 + l2 + 1
    seen: dict[tuple[int, int], int] = {}
    coords: list[tuple[int, int]] = []
    for x in range(-span, span + 1):
        for y in range(-span, span + 1):
            rep = _fold(x, y, l1, l2, n)
            if rep not in seen:
                seen[rep] = len(coords)
                coords.append(rep)
    if len(coords) != n:
        raise RuntimeError(
            f"tilted cell enumeration found {len(coords)} sites, expected {n} "
            f"for tilt ({l1}, {l2}) — folding window too small or fold() bug"
        )

    def site_of(x: int, y: int) -> int:
        return seen[_fold(x, y, l1, l2, n)]

    def _edges(displacements: list[tuple[int, int]]) -> list[tuple[int, int]]:
        es: set[tuple[int, int]] = set()
        for s, (x, y) in enumerate(coords):
            for dx, dy in displacements:
                t = site_of(x + dx, y + dy)
                if t == s:
                    continue  # degenerate wrap (only in tiny cells) — skip self-loop
                es.add((min(s, t), max(s, t)))
        return sorted(es)

    nn_edges = _edges([(1, 0), (0, 1)])
    nnn_edges = _edges([(1, 1), (1, -1)])

    return TiltedCluster(l1=l1, l2=l2, n_qubits=n, coords=coords, nn_edges=nn_edges, nnn_edges=nnn_edges)


# Magic numbers N = L1^2 + L2^2 mapped to a canonical tilt vector. For N <= 22
# each N has a single tilt; multi-tilt N (25 = 5²+0² = 4²+3², ...) appear above
# the exact-diagonalization reach and list the higher-symmetry (axis-aligned)
# tilt first.
MAGIC_TILTS: dict[int, tuple[int, int]] = {
    4: (2, 0),
    5: (2, 1),
    8: (2, 2),
    9: (3, 0),
    10: (3, 1),
    13: (3, 2),
    16: (4, 0),
    17: (4, 1),
    18: (3, 3),
    20: (4, 2),
    25: (5, 0),
    26: (5, 1),
    32: (4, 4),
    36: (6, 0),
    40: (6, 2),
}


def tilted_for_n(n: int) -> TiltedCluster:
    """Build the canonical tilted cluster for a magic N, or raise if N is not magic."""
    if n not in MAGIC_TILTS:
        raise ValueError(f"N={n} is not a tilted magic number. Available: {sorted(MAGIC_TILTS)}")
    l1, l2 = MAGIC_TILTS[n]
    return generate_square_tilted(l1, l2)
