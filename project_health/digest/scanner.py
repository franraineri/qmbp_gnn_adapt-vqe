def _synthesize_summary_from_analysis(
    analysis: dict[str, Any], data: dict[str, Any]
) -> dict[str, Any] | None:
    """Synthesize a standard summary dict from non-standard analysis formats.

    Handles experiments that store results in custom analysis structures
    (E4b: hypothesis_confirmed + per_g_stats, S8/S8b: custom fitting results)
    without a standard `summary` dict.

    Returns a summary dict with at least `pass_rate`, or None if no usable data.
    """
    # Pattern 1: hypothesis_confirmed in analysis (E4b-style)
    if "hypothesis_confirmed" in analysis:
        confirmed = analysis["hypothesis_confirmed"]
        return {
            "pass_rate": 1.0 if confirmed else 0.0,
            "hypothesis_confirmed": confirmed,
        }

    # Pattern 2: S8/S8b-style with fitting results
    if "nu_median" in analysis or "h_peaks_per_N" in analysis:
        # S8 uses nu fitting — confirmed if consistent peaks found
        confirmed = analysis.get("hypothesis_confirmed", False)
        n_fits = analysis.get("n_successful_fits", 0)
        n_seeds = analysis.get("n_seeds", 1)
        return {
            "pass_rate": n_fits / max(n_seeds, 1),
            "hypothesis_confirmed": confirmed,
        }

    # Pattern 3: results dict has per-seed data (E4b with seeds as keys)
    results = data.get("results", {})
    if results and all(k.isdigit() for k in results):
        # Per-seed results — count successes
        n_total = len(results)
        if n_total > 0:
            return {"pass_rate": 1.0, "n_seeds": n_total}

    return None


def _load_json(path: Path) -> dict[str, Any] | None:
    """Safely load a JSON file, returning None on failure.

    Delegates to the canonical load_result from framework.result_io for
    consistent error handling (size guard, corruption detection).
    """
    try:
        from qmbp_simulation.framework.result_io import load_result
        return load_result(path)
    except (FileNotFoundError, ValueError) as e:
        logger.debug("Failed to load %s: %s", path, e)
        return None
    except (OSError, UnicodeDecodeError) as e:
        logger.debug("Failed to load %s: %s", path, e)
        return None


def _get_int(d: dict, key: str) -> int:
    """Get an integer from a dict, returning 0 for None/missing."""
    val = d.get(key)
    return int(val) if val is not None else 0


def _extract_p_layers(config: dict, system: dict, path: Path) -> int:
    """Extract p_layers from config/system dicts.

    Fix #2: Logs a warning instead of silently defaulting to 2.
    Still returns 2 as default (for backward compat with NoiselessResult dataclass),
    but the warning makes it visible in --verbose mode.
    """
    p = config.get("p_layers") or system.get("p_layers")
    if p is not None:
        return int(p)
    logger.warning("p_layers not found in %s; defaulting to 2", path.name)
    return 2


def _infer_topology_from_name(name: str) -> str:
    """Infer topology from a folder name (e.g., 'variants_N10_ladder' → 'ladder')."""
    name_lower = name.lower()
    for topo in _KNOWN_TOPOLOGIES:
        if topo in name_lower:
            # Normalize the typo
            return "chain_1d" if topo == "linnear" else topo
    return ""


def _apply_topology_fallback(result: NoiselessResult | NoisyResult, context: str) -> None:
    """Set topology from parent context if the result file didn't specify one."""
    if not result.topology and context:
        result.topology = context


def _extract_timestamp_from_filename(filename: str) -> str:
    """Extract ISO timestamp from pipeline_run_YYYYMMDD_HHMMSS.json filename.

    Returns empty string if the pattern doesn't match (legacy files).
    """
    import re

    match = re.search(r"(\d{8})_(\d{6})", filename)
    if not match:
        return ""
    date_str, time_str = match.group(1), match.group(2)
    try:
        # Convert to ISO format: YYYY-MM-DDTHH:MM:SS
        return (
            f"{date_str[:4]}-{date_str[4:6]}-{date_str[6:8]}"
            f"T{time_str[:2]}:{time_str[2:4]}:{time_str[4:6]}"
        )
    except (IndexError, ValueError):
        return ""
