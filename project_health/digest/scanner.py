# Folders to skip during recursive scanning
_SKIP_FOLDERS = frozenset({"checkpoints", "__pycache__", ".DS_Store"})


class ResultScanner:
    """Scans all result directories and classifies files by kind."""

    # Known test artifact experiment IDs (generated by test_runner_base.py).
    # These are valid test outputs but should NOT appear in analysis reports.
    # NOTE: T1a/T1b/T1c are REAL experiments — test artifacts use "TEST_T1A" etc.
    TEST_ARTIFACT_IDS: set[str] = {
        "TEST",
        "FAIL",
        "XFAIL",
        "NONE",
        "CNT",
    }

    def __init__(self, results_root: Path = Path("results")) -> None:
        self.root = results_root
        self._exclude_tests = False
        self._index: Any = None

    @property
    def index(self):
        """Lazily-initialized ResultIndex for fast experiment discovery."""
        if self._index is None:
            from qmbp_simulation.framework.result_index import ResultIndex
            exp_root = self.root / "experiments"
            self._index = ResultIndex(root=exp_root)
        return self._index

    def scan_all(
        self,
        *,
        exclude_tests: bool = False,
    ) -> tuple[list[NoiselessResult], list[NoisyResult], list[ExperimentResult]]:
        """Scan all result areas and return typed results.

        Parameters
        ----------
        exclude_tests : bool
            If True, filter out known test artifact experiments (T1A, TEST, FAIL, etc.)
            that are generated by test_runner_base.py. Default: False for backward compat.
        """
        self._exclude_tests = exclude_tests
        noiseless: list[NoiselessResult] = []
        noisy: list[NoisyResult] = []
        experiments: list[ExperimentResult] = []

        # Scan results/experiments/
        exp_root = self.root / "experiments"
        if exp_root.exists():
            exp_dirs = [
                d
                for d in sorted(exp_root.iterdir())
                if d.is_dir() and d.name.startswith("exp_") and d.name != "exp_noisy_variants"
            ]
            logger.info("Scanning %d experiment directories...", len(exp_dirs))
            for exp_dir in exp_dirs:
                # Skip directories with empty name after prefix (e.g., "exp_/")
                if exp_dir.name == "exp_":
                    continue
                result = self._parse_experiment_dir(exp_dir)
                if result:
                    # Filter test artifacts if requested
                    if exclude_tests and result.experiment_id in self.TEST_ARTIFACT_IDS:
                        continue
                    # Skip results with empty experiment_id
                    if not result.experiment_id:
                        continue
                    experiments.append(result)
            logger.info("  → %d experiments parsed", len(experiments))

        # Scan results/thesis/
        thesis_root = self.root / "thesis"
        if thesis_root.exists():
            folders = [
                f
                for f in sorted(thesis_root.iterdir())
                if f.is_dir() and not f.name.startswith(".")
            ]
            logger.info("Scanning %d thesis folders...", len(folders))
            for folder in folders:
                context = _infer_topology_from_name(folder.name)
                self._scan_folder_recursive(folder, noiseless, noisy, parent_context=context)
            logger.info("  → %d noiseless, %d noisy results", len(noiseless), len(noisy))

        return noiseless, noisy, experiments

    def scan_folder(
        self, folder_name: str
    ) -> tuple[list[NoiselessResult], list[NoisyResult], list[ExperimentResult]]:
        """Scan a specific folder by name (searches experiments/ then thesis/)."""
        noiseless: list[NoiselessResult] = []
        noisy: list[NoisyResult] = []
        experiments: list[ExperimentResult] = []

        # Try experiments/
        exp_path = self.root / "experiments" / folder_name
        if exp_path.exists() and exp_path.is_dir():
            result = self._parse_experiment_dir(exp_path)
            if result:
                experiments.append(result)
            return noiseless, noisy, experiments

        # Try thesis/ exact match
        thesis_path = self.root / "thesis" / folder_name
        if thesis_path.exists() and thesis_path.is_dir():
            context = _infer_topology_from_name(folder_name)
            self._scan_folder_recursive(thesis_path, noiseless, noisy, parent_context=context)
            return noiseless, noisy, experiments

        # Try thesis/ substring match
        thesis_root = self.root / "thesis"
        if thesis_root.exists():
            for folder in sorted(thesis_root.iterdir()):
                if folder.is_dir() and folder_name.lower() in folder.name.lower():
                    context = _infer_topology_from_name(folder.name)
                    self._scan_folder_recursive(folder, noiseless, noisy, parent_context=context)

        return noiseless, noisy, experiments

    # ── Scaling results ─────────────────────────────────────────────────

    def scan_scaling(self) -> list[ScalingResult]:
        """Scan for MPS scaling validation results.

        Looks for ``scaling_N*_*.json`` files in ``results/scaling/``
        (relative to self.root's parent, since root is usually results/).
        Falls back to ``Path("results/scaling")`` if the primary path
        doesn't exist.

        Returns
        -------
        list[ScalingResult]
            Parsed scaling results, one per JSON file.
        """
        # Primary: self.root / "scaling" (root is usually "results/")
        scaling_dir = self.root / "scaling"
        if not scaling_dir.exists():
            # Fallback: relative to CWD
            scaling_dir = Path("results/scaling")

        if not scaling_dir.exists():
            logger.debug("No scaling results directory found")
            return []

        results: list[ScalingResult] = []
        for path in sorted(scaling_dir.glob("scaling_N*_*.json")):
            parsed = self._parse_scaling_file(path)
            if parsed:
                results.append(parsed)

        logger.info("Scanned %d scaling result files from %s", len(results), scaling_dir)
        return results

    def _parse_scaling_file(self, path: Path) -> ScalingResult | None:
        """Parse a scaling_N*_*.json into a ScalingResult."""
        data = _load_json(path)
        if not data:
            return None

        if data.get("experiment") != "mps_scaling_validation":
            return None

        meta = data.get("metadata", {})
        timing = data.get("timing", {})
        summary = data.get("summary", {})
        vqe_results = data.get("vqe_results", [])

        # Collect per-h metrics from all seed runs
        per_h_de_gap: list[float] = []
        per_h_passed: list[bool] = []
        for seed_run in vqe_results:
            for r in seed_run.get("results", []):
                per_h_de_gap.append(r.get("de_gap", 0.0))
                per_h_passed.append(r.get("passed", False))

        n_pass = summary.get("n_pass", 0)
        n_total = summary.get("n_total", 0)
        all_passed = summary.get("all_passed", False)
        mean_de = float(sum(per_h_de_gap) / max(len(per_h_de_gap), 1))
        max_de = float(max(per_h_de_gap)) if per_h_de_gap else 0.0

        seeds = meta.get("seeds", [42])
        seed = seeds[0] if seeds else 42

        return ScalingResult(
            source_file=str(path),
            folder=path.parent.name,
            n_qubits=meta.get("n", 0),
            p_layers=meta.get("p_layers", 1),
            topology=meta.get("topology", "chain_1d"),
            strategy=meta.get("strategy", "aer_mps"),
            chi_max=meta.get("chi_max", 64),
            precision=meta.get("precision", 0.005),
            seed=seed,
            h_values=meta.get("h_values", []),
            n_pass=n_pass,
            n_total=n_total,
            all_passed=all_passed,
            mean_de_gap=mean_de,
            max_de_gap=max_de,
            phase1_time_s=timing.get("phase1_dmrg_s", 0.0),
            phase2_time_s=timing.get("phase2_vqe_s", 0.0),
            total_time_s=timing.get("total_s", 0.0),
            per_h_de_gap=per_h_de_gap,
            per_h_passed=per_h_passed,
        )

