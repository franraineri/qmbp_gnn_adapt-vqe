    def _parse_noisy_file(self, path: Path, folder: str) -> NoisyResult | None:
        """Parse a noisy_*.json into a NoisyResult."""
        data = _load_json(path)
        if not data:
            return None

        config = data.get("config", {})
        system = data.get("system", {})
        summary = data.get("summary", {})
        per_h = data.get("results_per_h", [])

        # Extract p_layers with warning (Fix #2)
        p_layers = _extract_p_layers(config, system, path)

        # Detect ZNE strategy from config or filename
        zne_strategy = config.get("zne_strategy", "") or config.get("amplifier", "")
        if not zne_strategy:
            fname_lower = path.name.lower()
            if "pea" in fname_lower:
                zne_strategy = "pea"
            elif "gf" in fname_lower or "gate_folding" in fname_lower:
                zne_strategy = "gate_folding"
            elif "ces" in fname_lower:
                zne_strategy = "ces"

        return NoisyResult(
            source_file=str(path),
            folder=folder,
            n_qubits=_get_int(config, "n_qubits") or _get_int(system, "n_qubits"),
            p_layers=p_layers,
            topology=config.get("topology") or system.get("topology", ""),
            seed=config.get("seed", 42),
            n_layouts=config.get("n_layouts", 3),
            shots=config.get("shots", 16384),
            h_values=config.get("h_values", []),
            zne_strategy=zne_strategy,
            mean_r2=summary.get("mean_r2", 0),
            mean_gain_pct=summary.get("mean_gain_pct", 0),
            n_mitigated_wins=summary.get("n_mitigated_wins", 0),
            n_total=summary.get("n_total", 0),
            success_criteria_met=summary.get("success_criteria_met", False),
            mean_de_noiseless=summary.get("mean_de_noiseless", 0),
            mean_de_noisy_raw=summary.get("mean_de_noisy_raw", 0),
            mean_de_zne=summary.get("mean_de_zne", 0),
            per_h_r2=[p.get("r_squared", 0) for p in per_h],
            per_h_gain=[p.get("gain_pct", 0) for p in per_h],
            elapsed_s=summary.get("elapsed_s", 0),
            variant_id=folder,
        )

    def _parse_experiment_dir(self, exp_dir: Path) -> ExperimentResult | None:
        """Parse an experiment directory (exp_<id>/) into ExperimentResult.

        Handles both BaseExperiment and ValidationRunner result formats:
        - BaseExperiment: data["analysis"]["summary"] with mean_de_gap, pass_rate
        - ValidationRunner: data["summary"] with n_passed, pass_rate, hypotheses

        Uses recursive glob to support nested directory structures
        (e.g., exp_noiseless/tfim/heavy_hex/run_*.json).
        """
        run_files = sorted(exp_dir.rglob("run_*.json"), reverse=True)
        if not run_files:
            return None

        data = _load_json(run_files[0])
        if not data:
            return None

        config = data.get("config", {})
        analysis = data.get("analysis", {})
        summary = analysis.get("summary", {})
        system = config.get("system", {})

        # ValidationRunner format: summary at top level with pass_rate
        # (the _build_envelope also mirrors it into analysis.summary)
        if not summary and "summary" in data:
            summary = data["summary"]
            # Build a compatible analysis dict
            if not analysis:
                analysis = {"summary": summary, "n_seeds": len(config.get("seeds", []))}

        if not summary or "error" in summary:
            # Try to synthesize a summary from analysis-level data
            # (covers E4b, S8, S8b which use non-standard formats)
            synthesized = _synthesize_summary_from_analysis(analysis, data)
            if synthesized:
                summary = synthesized
            else:
                return None

        exp_id = config.get("experiment_id", exp_dir.name.replace("exp_", "").upper())

        # Safe category extraction (handles multi-word IDs like "MPS_HW")
        category = config.get("category", "")
        if not category and exp_id:
            category = exp_id[0] if len(exp_id) > 0 else ""

        # Compute verdict using centralized criteria
        verdict, criteria_desc = compute_verdict(exp_id, summary)

        # ValidationRunner: extract hypotheses info for richer reporting
        extras: dict[str, Any] = {}
        hypotheses = summary.get("hypotheses") or data.get("summary", {}).get("hypotheses")
        if hypotheses:
            extras["hypotheses"] = hypotheses
            extras["n_hypotheses"] = len(hypotheses)
            extras["n_confirmed"] = sum(1 for v in hypotheses.values() if v)
            # Override verdict based on hypotheses if compute_verdict gives generic result
            if all(hypotheses.values()):
                verdict = "confirmed"
                criteria_desc = (
                    f"{extras['n_confirmed']}/{extras['n_hypotheses']} hypotheses confirmed"
                )
            elif any(hypotheses.values()):
                verdict = "confirmed"
                criteria_desc = (
                    f"{extras['n_confirmed']}/{extras['n_hypotheses']} hypotheses confirmed "
                    f"(partial)"
                )

        # ValidationRunner: extract per-section summary
        results_data = data.get("results", {})
        if results_data and any(k.startswith("section_") for k in results_data):
            sections_info = []
            for k in sorted(results_data.keys()):
                if k.startswith("section_"):
                    sec = results_data[k]
                    sections_info.append(
                        {
                            "name": sec.get("name", k),
                            "success": sec.get("success"),
                            "elapsed_s": sec.get("elapsed_s", 0),
                        }
                    )
            extras["sections"] = sections_info

        # Experiment-specific extras (legacy)
        if exp_id == "A3":
            extras["scaling_law_fit"] = analysis.get("scaling_law_fit", {})
        elif exp_id == "G1":
            extras["data_efficiency"] = analysis.get("data_efficiency", {})

        # Extract p_layers
        p_layers_val = system.get("p_layers") or config.get("p_layers")
        p_layers = int(p_layers_val) if p_layers_val is not None else 2

        # Extract model type
        model_type = system.get("model") or config.get("model", "tfim")

        return ExperimentResult(
            source_file=str(run_files[0]),
            folder=exp_dir.name,
            experiment_id=exp_id,
            category=category,
            hypothesis=config.get("hypothesis", ""),
            description=config.get("description", ""),
            n_qubits=system.get("n_qubits", 0),
            p_layers=p_layers,
            topology=system.get("topology", ""),
            model=model_type,
            h_values=system.get("h_values", []),
            seeds=config.get("seeds", []),
            verdict=verdict,
            criteria=criteria_desc,
            mean_de_gap=summary.get("mean_de_gap"),
            std_de_gap=summary.get("std_de_gap"),
            pass_rate=summary.get("pass_rate"),
            n_seeds=analysis.get("n_seeds", len(config.get("seeds", []))),
            total_time_s=summary.get("total_time_s") or summary.get("total_elapsed_s", 0),
            extras=extras,
        )


