#!/usr/bin/env python3
"""Cross-topology transfer experiment: train on topology A, predict topology B.

Trains a GNN (MPNNPredictor) on VQE optimal parameters from one lattice
topology and predicts parameters for a structurally different topology.
Runs both directions (triangular→heavy_hex and heavy_hex→triangular) in
a single experiment with a comparison table.

Key design decisions:
- Uses TARGET topology's edge_index and coordination numbers for prediction
- Node features: (h, coordination_number, N/100) — GNN captures topology
- Evaluates variational principle for every prediction
- Reports both directions with mean ΔE/gap, pass rate, variational_ok

Usage:
    python scripts/experiment_runners/cross_topology/run_cross_topology.py \\
        --source-topologies triangular heavy_hex \\
        --target-n 10 \\
        --seeds 42,43,44 \\
        --output-dir results/scaling/cross_topology

Requirements: 4.1, 4.2, 4.3, 4.4, 4.5, 4.6, 4.7, 8.1
"""

