# ═══════════════════════════════════════════════════════════════════════════════
# h-value regimes for target prediction
# ═══════════════════════════════════════════════════════════════════════════════

# Target h-values for N=10 prediction (within valid regime)
# triangular N=10: h >= 4.0 (project-status.md: valid regime p=1)
# heavy_hex N=10: h >= 3.25 (validated)
TARGET_H_VALUES: dict[str, list[float]] = {
    "triangular": [5.5, 5.0, 4.5, 4.25, 4.0],
    "heavy_hex": [5.0, 4.5, 4.0, 3.5, 3.25],
}


def get_target_h_values(topology: str, n: int) -> list[float]:
    """Get appropriate h-values for target prediction.

    Uses validated valid-regime boundaries per topology.
    """
    if topology in TARGET_H_VALUES:
        return TARGET_H_VALUES[topology]
    # Fallback: compute from scaling law + safety margin
    h_min = 1.5 + 0.020 * n**1.31 + 0.5
    h_max = h_min + 2.0
    return np.linspace(h_max, h_min, 5).tolist()


# ═══════════════════════════════════════════════════════════════════════════════
# Single-direction transfer experiment
# ═══════════════════════════════════════════════════════════════════════════════


def run_single_direction(
    source_files: list[Path],
    source_topology: str,
    target_topology: str,
    target_n: int,
    seed: int,
    hidden_dim: int = 128,
    n_epochs: int = 6000,
    norm_type: str = "none",
    threshold: float = 0.10,
) -> dict:
    """Train on source topology, predict on target topology for one seed.

    Parameters
    ----------
    source_files : list[Path]
        Paths to VQE result JSON files for the source topology.
    source_topology : str
        Source topology name (e.g. "triangular").
    target_topology : str
        Target topology name (e.g. "heavy_hex").
    target_n : int
        Target system size for prediction.
    seed : int
        Random seed for training reproducibility.
    hidden_dim : int
        GNN hidden dimension.
    n_epochs : int
        Training epochs.
    norm_type : str
        Normalization type for MPNNPredictor.
    threshold : float
        Pass threshold for ΔE/gap.

    Returns
    -------
    dict
        Direction result with training metrics, predictions, and summary.
    """
    direction = f"{source_topology}→{target_topology}"
    logger.info(f"\n{'─' * 60}")
    logger.info(f"  Direction: {direction} (seed={seed})")
    logger.info(f"{'─' * 60}")

    t_direction_start = time.perf_counter()

    # Load source data with quality filtering
    sources = []
    source_file_strs = []
    for sf in source_files:
        try:
            src = load_source_data_filtered(sf, seed=seed)
            sources.append(src)
            source_file_strs.append(str(sf))
            logger.info(f"  Loaded: {sf.name} (N={src.n}, {len(src.h_values)} h-points)")
        except (FileNotFoundError, ValueError) as e:
            logger.warning(f"  Skip {sf}: {e}")
            continue

    if not sources:
        logger.error(f"  No valid source data for {direction}")
        return {"error": f"No source data found for {source_topology}", "direction": direction}

    # ── Validate training data ──────────────────────────────────────
    validation = validate_training_data(
        sources,
        min_points=6,
        min_sizes=2,
        experiment_label=direction,
    )
    if not validation.passed:
        logger.error(
            f"  Training data validation FAILED for {direction}. Errors: {validation.errors}"
        )
        return {
            "error": f"Training data validation failed: {validation.errors}",
            "direction": direction,
            "validation_report": validation.to_dict(),
        }

    # Determine output dimension from source data
    output_dim = sources[0].param_dim
    logger.info(
        f"  Training data: {sum(len(s.h_values) for s in sources)} points, output_dim={output_dim}"
    )

    # Build torch_geometric dataset from source topology data
    dataset = build_cross_topology_dataset(sources, use_n_feature=True)
    logger.info(f"  Dataset: {len(dataset)} graphs")

    # Train MPNN
    model = MPNNPredictor(
        node_features=3,
        hidden_dim=hidden_dim,
        n_layers=3,
        output_dim=output_dim,
        norm_type=norm_type,
    )
    n_params = sum(p.numel() for p in model.parameters())
    logger.info(
        f"  Model: MPNNPredictor(hidden={hidden_dim}, norm={norm_type}), {n_params:,} params"
    )

    t_train_start = time.perf_counter()
    train_metrics = train_mpnn(model, dataset, n_epochs=n_epochs, seed=seed)
    t_train = time.perf_counter() - t_train_start
    logger.info(f"  Training: MSE={train_metrics['final_mse']:.2e}, time={t_train:.1f}s")

    # Deploy on TARGET topology
    # CRITICAL: build_target_graph uses TARGET topology's edge_index and coord
    model.eval()
    h_test = get_target_h_values(target_topology, target_n)
    logger.info(
        f"  Predicting {target_topology} N={target_n}, h_test={[f'{h:.2f}' for h in h_test]}"
    )

    predictions = []
    for h_val in h_test:
        # Build target graph with TARGET topology structure
        target_graph = build_target_graph(target_topology, target_n, h_val, use_n_feature=True)

        # Predict theta
        with torch.no_grad():
            theta_pred = model(target_graph).numpy().flatten()
        theta_pred = canonicalize_theta(theta_pred)

        # Evaluate on target system
        result = evaluate_theta(
            theta_pred=theta_pred,
            n_target=target_n,
            h_val=h_val,
            topology=target_topology,
            threshold=threshold,
            seed=seed,
        )
        predictions.append(result)

        status = "✅" if result["passed"] else "❌"
        var_flag = "" if result["variational_ok"] else " ⚠VARIATIONAL"
        logger.info(
            f"    {status} h={h_val:.2f}: ΔE/gap={result['de_gap'] * 100:.3f}%"
            f"{var_flag} ({result['time_s']:.1f}s)"
        )

    t_direction_total = time.perf_counter() - t_direction_start

    # Compute summary metrics
    de_gaps = [r["de_gap"] for r in predictions]
    n_pass = sum(1 for r in predictions if r["passed"])
    n_variational_ok = sum(1 for r in predictions if r["variational_ok"])

    # Log warnings for failures
    if n_pass < 3:
        logger.warning(
            f"  ⚠️ {direction} FAILED (seed={seed}): only {n_pass}/{len(h_test)} passed "
            f"(need ≥3). Mean ΔE/gap={np.mean(de_gaps) * 100:.2f}%"
        )
    if n_variational_ok < len(h_test):
        logger.warning(
            f"  ⚠️ Variational principle violated for "
            f"{len(h_test) - n_variational_ok}/{len(h_test)} points "
            f"({direction}, seed={seed})"
        )
    if t_direction_total > 2700:  # 45 min per direction is concerning (90 min budget / 2)
        logger.warning(
            f"  ⚠️ {direction} took {t_direction_total / 60:.1f}m — approaching budget limit"
        )

    # ── Post-prediction sanity check ─────────────────────────────────
    pred_sanity = validate_predictions_sanity(
        predictions,
        target_topology,
        target_n,
        experiment_label=direction,
    )
    if not pred_sanity.passed:
        logger.error(
            f"  Predictions are physically unreasonable for {direction}. "
            f"This indicates a fundamental problem (not just poor accuracy)."
        )

    summary = {
        "direction": direction,
        "source_topology": source_topology,
        "target_topology": target_topology,
        "target_n": target_n,
        "seed": seed,
        "source_files": source_file_strs,
        "source_sizes": sorted(set(s.n for s in sources)),
        "n_training_points": len(dataset),
        "model_params": n_params,
        "training": {
            "final_mse": train_metrics["final_mse"],
            "stopped_early": train_metrics.get("stopped_early", False),
            "time_s": t_train,
        },
        "predictions": predictions,
        "metrics": {
            "mean_de_gap": float(np.mean(de_gaps)),
            "max_de_gap": float(np.max(de_gaps)),
            "min_de_gap": float(np.min(de_gaps)),
            "std_de_gap": float(np.std(de_gaps)),
            "n_pass": n_pass,
            "n_total": len(h_test),
            "pass_rate": n_pass / len(h_test),
            "variational_ok_count": n_variational_ok,
            "variational_ok_all": n_variational_ok == len(h_test),
        },
        "timing": {
            "training_s": t_train,
            "prediction_s": sum(r["time_s"] for r in predictions),
            "total_s": t_direction_total,
        },
    }

    logger.info(
        f"  Summary: mean ΔE/gap={np.mean(de_gaps) * 100:.3f}%, "
        f"pass={n_pass}/{len(h_test)}, "
        f"variational_ok={n_variational_ok}/{len(h_test)}, "
        f"time={t_direction_total:.1f}s"
    )

    return summary


# ═══════════════════════════════════════════════════════════════════════════════
# Multi-seed aggregation
# ═══════════════════════════════════════════════════════════════════════════════


def aggregate_seed_results(seed_results: list[dict]) -> dict:
    """Aggregate results across multiple seeds.

    Returns mean and std of key metrics.
    """
    valid_results = [r for r in seed_results if "error" not in r]
    if not valid_results:
        return {"error": "All seeds failed"}

    mean_de_gaps = [r["metrics"]["mean_de_gap"] for r in valid_results]
    pass_rates = [r["metrics"]["pass_rate"] for r in valid_results]
    var_ok_counts = [r["metrics"]["variational_ok_count"] for r in valid_results]

    return {
        "n_seeds": len(valid_results),
        "seeds": [r["seed"] for r in valid_results],
        "mean_de_gap": {
            "mean": float(np.mean(mean_de_gaps)),
            "std": float(np.std(mean_de_gaps)),
            "per_seed": mean_de_gaps,
        },
        "pass_rate": {
            "mean": float(np.mean(pass_rates)),
            "std": float(np.std(pass_rates)),
            "per_seed": pass_rates,
        },
        "variational_ok_count": {
            "mean": float(np.mean(var_ok_counts)),
            "per_seed": var_ok_counts,
        },
        "per_seed_results": valid_results,
    }


# ═══════════════════════════════════════════════════════════════════════════════
# Main
# ═══════════════════════════════════════════════════════════════════════════════


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Cross-topology transfer: train on topology A, predict topology B",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--source-topologies",
        type=str,
        nargs="+",
        default=["triangular", "heavy_hex"],
        help="Source topologies to train on (each becomes a direction)",
    )
    parser.add_argument(
        "--target-n",
        type=int,
        default=10,
        help="Target system size for prediction",
    )
    parser.add_argument(
        "--norm-type",
        type=str,
        default="none",
        choices=["batch", "layer", "none"],
        help="Normalization type for MPNNPredictor",
    )
    parser.add_argument(
        "--seeds",
        type=str,
        default="42,43,44",
        help="Comma-separated random seeds",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="results/scaling/cross_topology",
        help="Output directory for result JSON",
    )
    parser.add_argument(
        "--epochs",
        type=int,
        default=6000,
        help="Number of training epochs",
    )
    parser.add_argument(
        "--hidden-dim",
        type=int,
        default=128,
        help="GNN hidden dimension",
    )
    parser.add_argument(
        "--source-files-tri",
        type=str,
        nargs="*",
        default=None,
        help="Explicit source files for triangular topology (all sizes)",
    )
    parser.add_argument(
        "--source-files-hex",
        type=str,
        nargs="*",
        default=None,
        help="Explicit source files for heavy_hex topology (all sizes)",
    )
    parser.add_argument(
        "--threshold",
        type=float,
        default=0.10,
        help="ΔE/gap pass threshold (default 10%%)",
    )
    args = parser.parse_args()

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s [%(levelname)s] %(message)s",
    )

    # Parse seeds
    seeds = [int(s.strip()) for s in args.seeds.split(",")]
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Log experiment parameters
    logger.info("=" * 60)
    logger.info("Cross-Topology Transfer Experiment")
    logger.info("=" * 60)
    logger.info(f"  Source topologies: {args.source_topologies}")
    logger.info(f"  Target N: {args.target_n}")
    logger.info(f"  Norm type: {args.norm_type}")
    logger.info(f"  Seeds: {seeds}")
    logger.info(f"  Epochs: {args.epochs}")
    logger.info(f"  Hidden dim: {args.hidden_dim}")
    logger.info(f"  Threshold: {args.threshold * 100:.0f}%")
    logger.info(f"  Output dir: {output_dir}")
    logger.info("=" * 60)

    t_experiment_start = time.perf_counter()

    # Resolve source files for each topology
    source_files_map: dict[str, list[Path]] = {}

    if args.source_files_tri:
        source_files_map["triangular"] = [Path(f) for f in args.source_files_tri]
    if args.source_files_hex:
        source_files_map["heavy_hex"] = [Path(f) for f in args.source_files_hex]

    # Auto-discover source files from default directories if not explicit
    for topo in args.source_topologies:
        if topo not in source_files_map:
            discovered = _discover_source_files(topo, output_dir)
            if discovered:
                source_files_map[topo] = discovered
                logger.info(f"  Auto-discovered {len(discovered)} files for {topo}")
            else:
                logger.error(
                    f"  No source files found for {topo}. "
                    f"Use --source-files-tri or --source-files-hex to specify."
                )
                return 1

    # Run bidirectional transfer
    # Direction 1: tri→hex (train on triangular, predict heavy_hex)
    # Direction 2: hex→tri (train on heavy_hex, predict triangular)
    all_directions: dict[str, dict] = {}

    for source_topo in args.source_topologies:
        # Target is the OTHER topology
        target_topo = _get_target_topology(source_topo, args.source_topologies)
        if target_topo is None:
            logger.warning(f"  No target topology for {source_topo}, skipping")
            continue

        direction_key = f"{source_topo[:3]}_to_{target_topo[:3]}"
        seed_results = []

        for seed in seeds:
            result = run_single_direction(
                source_files=source_files_map[source_topo],
                source_topology=source_topo,
                target_topology=target_topo,
                target_n=args.target_n,
                seed=seed,
                hidden_dim=args.hidden_dim,
                n_epochs=args.epochs,
                norm_type=args.norm_type,
                threshold=args.threshold,
            )
            seed_results.append(result)

        # Aggregate across seeds
        aggregated = aggregate_seed_results(seed_results)
        all_directions[direction_key] = aggregated

    t_experiment_total = time.perf_counter() - t_experiment_start

    # Print comparison table
    logger.info(f"\n{'═' * 60}")
    logger.info("  COMPARISON TABLE: Cross-Topology Transfer")
    logger.info(f"{'═' * 60}")
    logger.info(f"  {'Direction':<20} {'Mean ΔE/gap':<15} {'Pass Rate':<12} {'Var OK':<10}")
    logger.info(f"  {'─' * 57}")

    for dir_key, agg in all_directions.items():
        if "error" in agg:
            logger.info(f"  {dir_key:<20} {'ERROR':<15} {'—':<12} {'—':<10}")
            continue
        mean_de = agg["mean_de_gap"]["mean"]
        pass_rate = agg["pass_rate"]["mean"]
        var_ok_mean = agg["variational_ok_count"]["mean"]
        logger.info(
            f"  {dir_key:<20} {mean_de * 100:.3f}%{'':<9} "
            f"{pass_rate * 100:.0f}%{'':<8} "
            f"{var_ok_mean:.1f}/5"
        )

    logger.info(f"  {'─' * 57}")
    logger.info(f"  Total time: {t_experiment_total:.1f}s ({t_experiment_total / 60:.1f}m)")

    if t_experiment_total > 5400:  # 90 min
        logger.warning(f"  ⚠️ Exceeded 90-min budget: {t_experiment_total / 60:.1f}m")

    # Build result envelope
    all_source_files = []
    for files in source_files_map.values():
        all_source_files.extend(str(f) for f in files)

    envelope = build_experiment_envelope(
        experiment_name="cross_topology_transfer",
        source_files=all_source_files,
        seeds=seeds,
        target_n=args.target_n,
        norm_type=args.norm_type,
        hidden_dim=args.hidden_dim,
        epochs=args.epochs,
        threshold=args.threshold,
        total_time_s=t_experiment_total,
    )

    # Merge results into envelope
    envelope["cross_topology"] = all_directions
    envelope["comparison"] = _build_comparison_summary(all_directions, args.threshold)
    envelope["timing"] = {"total_s": t_experiment_total}

    # Save results
    timestamp = time.strftime("%Y%m%d_%H%M%S")
    out_path = output_dir / f"cross_topology_transfer_{timestamp}.json"
    json_dump(envelope, out_path)
    logger.info(f"\n  Results saved: {out_path}")

    # Return code: 0 if both directions pass (≥3/5), else 1
    all_pass = all(
        agg.get("pass_rate", {}).get("mean", 0) >= 0.6
        for agg in all_directions.values()
        if "error" not in agg
    )
    return 0 if all_pass else 1


# ═══════════════════════════════════════════════════════════════════════════════
# Utility functions
# ═══════════════════════════════════════════════════════════════════════════════


def _get_target_topology(source_topo: str, available_topos: list[str]) -> str | None:
    """Get the target topology (the other one in the pair)."""
    for t in available_topos:
        if t != source_topo:
            return t
    return None


def _discover_source_files(topology: str, cross_topo_dir: Path) -> list[Path]:
    """Auto-discover source VQE data files for a given topology.

    Searches in cross_topology output dir (from run_vqe_data_gen.py)
    and thesis result directories.
    """
    found: list[Path] = []

    # 1. Check cross_topology dir for VQE-generated data
    if cross_topo_dir.exists():
        for f in sorted(cross_topo_dir.glob(f"vqe_{topology}_*.json")):
            found.append(f)

    # 2. Check thesis directories for pipeline_run format data
    thesis_dirs = [
        Path("results/thesis/p1_variants_N10"),
        Path("results/thesis/p1_variants_N16_r2"),
        Path("results/thesis/verification_r1"),
    ]
    for td in thesis_dirs:
        if td.exists():
            for subdir in sorted(td.iterdir()):
                if not subdir.is_dir():
                    continue
                if topology not in subdir.name:
                    continue
                for f in sorted(subdir.glob("pipeline_run_*.json")):
                    found.append(f)

    return found


def _build_comparison_summary(all_directions: dict[str, dict], threshold: float) -> dict:
    """Build a summary comparison dict for the result JSON."""
    summary: dict[str, object] = {
        "threshold": threshold,
        "directions": {},
    }

    all_pass = True
    for dir_key, agg in all_directions.items():
        if "error" in agg:
            summary["directions"][dir_key] = {"status": "ERROR"}
            all_pass = False
            continue

        mean_de = agg["mean_de_gap"]["mean"]
        pass_rate = agg["pass_rate"]["mean"]
        direction_pass = pass_rate >= 0.6  # ≥3/5

        summary["directions"][dir_key] = {
            "mean_de_gap": mean_de,
            "mean_de_gap_pct": f"{mean_de * 100:.3f}%",
            "pass_rate": pass_rate,
            "status": "PASS" if direction_pass else "FAIL",
        }
        if not direction_pass:
            all_pass = False

    summary["overall_pass"] = all_pass
    summary["verdict"] = "PASS" if all_pass else "FAIL"
    return summary


if __name__ == "__main__":
    sys.exit(main())
