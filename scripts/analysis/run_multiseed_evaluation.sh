#!/bin/bash
# Multi-seed cross-topology evaluation — Option A (from-zoo, deterministic)
# Uses the pre-trained zoo model (iteratively improved) for evaluation.
# Results appended to results/multiseed_evaluation.md

set -e
SCRIPT="scripts/experiment_runners/bond_resolved/run_accelerated_cross_n.py"
REPORT="results/multiseed_evaluation.md"

# Append a new section (don't overwrite previous results)
cat >> "$REPORT" << EOF

---

# Option A: Zoo Model Evaluation (deterministic)

**Date**: $(date +%Y-%m-%d\ %H:%M)
**Method**: --from-zoo (pre-trained iteratively-improved model)
**Note**: MPNN prediction is deterministic — no seed variance expected.
This measures the final pipeline performance.

EOF

for TOPO in chain_1d heavy_hex square triangular; do
    case $TOPO in
        chain_1d)   HMIN=1.5; HMAX=5.5; N=10;;
        heavy_hex)  HMIN=1.4; HMAX=4.5; N=10;;
        square)     HMIN=2.0; HMAX=5.0; N=10;;
        triangular) HMIN=3.0; HMAX=5.5; N=6;;
    esac

    echo ">>> Running $TOPO N=$N (from-zoo) ..."
    .venv/bin/python "$SCRIPT" \
        --topology "$TOPO" --target-n "$N" --from-zoo \
        --h-min "$HMIN" --h-max "$HMAX" --h-points 25 \
        > "results/multiseed_zoo_${TOPO}.log" 2>&1 || true

    # Extract metrics from the latest result JSON
    RESULT_FILE=$(ls -t results/experiments/exp_accel_cross_n/run_*.json 2>/dev/null | head -1)

    if [ -n "$RESULT_FILE" ]; then
        METRICS=$(.venv/bin/python -c "
import json, sys
try:
    with open('$RESULT_FILE') as f:
        d = json.load(f)
    results_block = d.get('results', d.get('sections', {}))
    for key, sec in results_block.items():
        if not isinstance(sec, dict):
            continue
        search_in = [sec]
        if 'data' in sec and isinstance(sec['data'], dict):
            search_in.append(sec['data'])
        for container in search_in:
            if 'cross_n_results' in container:
                for k, v in container['cross_n_results'].items():
                    if 'pass_rate_5pct' in v:
                        p5 = v['pass_rate_5pct']
                        pd = v.get('pass_rate_dual', p5)
                        de = v.get('mean_de_gap', 0)
                        ae = v.get('mean_abs_error', 0)
                        fid = v.get('mean_fidelity', 0)
                        n_pts = v.get('n_points', 0)
                        print(f'{p5:.0%}|{pd:.0%}|{de:.4f}|{ae:.4f}|{fid:.4f}|{n_pts}')
                        sys.exit(0)
    print('no_data|—|—|—|—|—')
except Exception as e:
    print(f'error|—|—|—|—|{e}')
" 2>/dev/null)
        P5=$(echo "$METRICS" | cut -d'|' -f1)
        PD=$(echo "$METRICS" | cut -d'|' -f2)
        DE=$(echo "$METRICS" | cut -d'|' -f3)
        AE=$(echo "$METRICS" | cut -d'|' -f4)
        FID=$(echo "$METRICS" | cut -d'|' -f5)
        NPTS=$(echo "$METRICS" | cut -d'|' -f6)
        FNAME=$(basename "$RESULT_FILE")

        cat >> "$REPORT" << EOF
## $TOPO (N=$N, h=[$HMIN, $HMAX])

| Metric | Value |
|--------|-------|
| Pass@5% | $P5 |
| Pass@dual | $PD |
| Mean ΔE/gap | $DE |
| Mean |ΔE| | $AE |
| Mean Fidelity | $FID |
| Points | $NPTS |
| Result | \`$FNAME\` |

EOF
    else
        echo "## $TOPO — ERROR (no result file)" >> "$REPORT"
        echo "" >> "$REPORT"
    fi
done

echo "---" >> "$REPORT"
echo "" >> "$REPORT"
echo "*Generated by run_multiseed_evaluation.sh (Option A: from-zoo)*" >> "$REPORT"

echo ">>> Done! Report appended to: $REPORT"
